#!/usr/bin/env python3
"""
Generates training performance plots (reward curve and rolling success rate)
from the CSV log generated by TrainingLogger.
"""

import matplotlib
matplotlib.use('Agg')  # Forces non-interactive backend, preventing GUI errors
import matplotlib.pyplot as plt
import pandas as pd
import sys
import os

def main():
    # Default to package results path if no argument provided
    default_csv = os.path.expanduser(
        "~/com760_ws/src/com760cw2_group34/results/small_city/episode_log_20260724-095618.csv"
    )
    
    if len(sys.argv) > 1:
        csv_file = sys.argv[1]
    else:
        csv_file = default_csv

    if not os.path.exists(csv_file):
        print(f"Error: CSV file not found at {csv_file}")
        print("Usage: python3 plot_results.py <path_to_episode_log.csv>")
        return

    print(f"Reading training data from: {csv_file}")
    df = pd.read_csv(csv_file)

    # Determine output directory based on CSV location
    output_dir = os.path.dirname(csv_file)

    # Convert columns explicitly to numpy arrays
    episodes = df["episode"].to_numpy()
    rewards = df["total_reward"].to_numpy()
    
    # Calculate rolling success rate safely
    success = df["goal_reached"].to_numpy()
    success_series = pd.Series(success)
    success_rate = success_series.rolling(window=20, min_periods=1).mean().to_numpy()

    # Plot 1: Reward Curve
    plt.figure(figsize=(10, 5))
    plt.plot(episodes, rewards, color='blue', alpha=0.6, label='Total Reward')
    plt.title("Q-Learning Reward per Episode (Small City Navigation)")
    plt.xlabel("Episode")
    plt.ylabel("Total Reward")
    plt.grid(True)
    plt.legend()
    reward_path = os.path.join(output_dir, "reward_curve.png")
    plt.savefig(reward_path, dpi=300, bbox_inches='tight')
    plt.close()

    # Plot 2: Success Rate Curve
    plt.figure(figsize=(10, 5))
    plt.plot(episodes, success_rate * 100, color='green', linewidth=2, label='20-Ep Moving Average')
    plt.title("Delivery Success Rate (Moving Average)")
    plt.xlabel("Episode")
    plt.ylabel("Success Rate (%)")
    plt.ylim(-5, 105)
    plt.grid(True)
    plt.legend()
    success_path = os.path.join(output_dir, "success_rate.png")
    plt.savefig(success_path, dpi=300, bbox_inches='tight')
    plt.close()

    print(f"Successfully generated figures in: {output_dir}")
    print(f" - {reward_path}")
    print(f" - {success_path}")

if __name__ == "__main__":
    main()